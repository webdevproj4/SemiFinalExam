const parameters = new URLSearchParams(window.location.search);

const productID = parameters.get("id");

const product = products[productID];


// CHECK IF PRODUCT EXISTS
if (!product) {

    document.querySelector(".product-container").innerHTML =
        "<h2>Product not found!</h2>";
``
} else {

    // DISPLAY PRODUCT INFORMATION

    document.getElementById("product-name").textContent =
        product.name + " - " + product.description;

    document.getElementById("product-price").textContent =
        "₱" + product.price.toLocaleString("en-PH");

    document.getElementById("old-price").textContent =
        "₱" + product.oldPrice.toLocaleString("en-PH");

    document.getElementById("discount").textContent =
        "-" + product.discount + "%";

    document.getElementById("product-rating").textContent =
        product.rating.toFixed(1);

    document.getElementById("product-reviews").textContent =
        product.reviews + " Ratings";


    // DISPLAY MAIN IMAGE

    const mainImage = document.getElementById("main-image");

    mainImage.src = product.images[0];

    mainImage.alt = product.name;


    // DISPLAY SMALL IMAGES

    const thumbnailContainer =
        document.getElementById("thumbnail-container");

    product.images.forEach(function (image, index) {

        const thumbnail = document.createElement("img");

        thumbnail.src = image;

        thumbnail.alt = product.name + " image " + (index + 1);

        thumbnail.classList.add("thumbnail");

        // HIGHLIGHT FIRST IMAGE

        if (index === 0) {
            thumbnail.classList.add("active");
        }

        // CHANGE MAIN IMAGE WHEN CLICKED

        thumbnail.addEventListener("click", function () {

            mainImage.src = image;

            document.querySelectorAll(".thumbnail").forEach(function (item) {

                item.classList.remove("active");

            });

            thumbnail.classList.add("active");

        });

        thumbnailContainer.appendChild(thumbnail);

    });


    // QUANTITY BUTTONS

    let quantity = 1;

    const quantityDisplay = document.getElementById("quantity");


    // DECREASE QUANTITY

    document.getElementById("decrease").addEventListener("click", function () {

        if (quantity > 1) {

            quantity--;

            quantityDisplay.textContent = quantity;

        }

    });


    // INCREASE QUANTITY

    document.getElementById("increase").addEventListener("click", function () {

        quantity++;

        quantityDisplay.textContent = quantity;

    });
}